def f(s):
    #print(s)
    if s[:2] != "11": return 0
    exact = 2
    dp = [0]*5 # [0,1,even,odd,messedup]
    for i in range(2,len(s)):
        ndp = [0]*5
        if exact != -1: # compute the exact case
            if s[i] == "0":
                if exact % 2 == 0 or exact == 1:
                    exact = 0
                else: exact = -1
            else:
                if exact % 2 == 0 or exact == 1: # could transititon out
                    ndp[0] += 1
                exact += 1
        ndp[0] = (ndp[0]+dp[0]+dp[1]+dp[2]+dp[4]) % mod # 0 after 0/1/even 1s
